#!/usr/bin/env python3
"""Bundle the dashboard and the decision log into one self-contained HTML file.

The output has the log embedded, so it renders over file:// or any static host
with no server, no fetch and no file picker.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = '<script id="embedded-log" type="application/json"></script>'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--log", default=str(ROOT / "logs" / "decisions.jsonl"))
    parser.add_argument("--template", default=str(ROOT / "dashboard" / "index.html"))
    parser.add_argument("--out", default=str(ROOT / "dashboard" / "share.html"))
    parser.add_argument("--keep-account", action="store_true",
                        help="embed the paper account id instead of redacting it")
    args = parser.parse_args()

    log_path = Path(args.log)
    records = []
    for lineno, raw in enumerate(log_path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise SystemExit(f"{log_path}:{lineno}: invalid JSON ({exc})")
        if not args.keep_account:
            order = record.get("order")
            if isinstance(order, dict) and order.get("acc_id"):
                order["acc_id"] = "REDACTED"
            for check in record.get("risk_checks") or []:
                if isinstance(check, dict) and check.get("rule") == "paper_account":
                    check["value"] = check["limit"] = "REDACTED"
        records.append(record)
    if not records:
        raise SystemExit(f"{log_path}: nothing to embed")

    # JSONL text inside a <script> block: escape "<" so "</script>" can never appear.
    payload = "\n".join(
        json.dumps(record, ensure_ascii=False, separators=(",", ":")) for record in records
    )
    payload = (payload.replace("<", "\\u003c")
                      .replace("\u2028", "\\u2028")
                      .replace("\u2029", "\\u2029"))

    template = Path(args.template).read_text(encoding="utf-8")
    if template.count(MARKER) != 1:
        raise SystemExit(f"{args.template}: expected exactly one embedded-log marker")

    block = ('<!-- generated by src/export_dashboard.py -->\n'
             f'<script id="embedded-log" type="application/json">{payload}</script>')
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(template.replace(MARKER, block), encoding="utf-8")
    print(f"wrote {out_path} ({len(records)} records, {out_path.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
